"""Spec section 9: write the complete python-docx script for an approved resume.

The script is self-contained (imports, data, every helper, filename rules),
builds the document from a blank Document(), saves it, checks the file exists
and prints the path. `execute.py` runs it in a separate Python process.
"""
import inspect
import pprint

from .filename import sanitise_filename

_TEMPLATE = r'''#!/usr/bin/env python3
"""Builds the approved resume for __NAME__ as a Word document.

Generated by the Australian Resume Content and Word Generator.
Run:  python build_resume.py [output_directory]
Needs: python-docx (pip install python-docx)
"""
import os
import re
import sys

from docx import Document
from docx.enum.section import WD_ORIENT
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_LINE_SPACING
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Cm, Pt, RGBColor

FONT = "Calibri"
BLACK = RGBColor(0, 0, 0)
BODY_PT = 11

# The approved resume content. Wording is exactly as approved.
RESUME = __DATA__


__SANITISE__

def set_run_font(run, size=BODY_PT, bold=None, italic=None):
    """Calibri, black, fixed size, with Latin, East Asian and complex-script fonts all set."""
    run.font.name = FONT
    run.font.size = Pt(size)
    run.font.color.rgb = BLACK
    if bold is not None:
        run.font.bold = bold
    if italic is not None:
        run.font.italic = italic
    rpr = run._element.get_or_add_rPr()
    fonts = rpr.find(qn("w:rFonts"))
    if fonts is None:
        fonts = OxmlElement("w:rFonts")
        rpr.insert(0, fonts)
    for attr in ("w:ascii", "w:hAnsi", "w:eastAsia", "w:cs"):
        fonts.set(qn(attr), FONT)
    for attr in ("w:asciiTheme", "w:hAnsiTheme", "w:eastAsiaTheme", "w:cstheme"):
        fonts.attrib.pop(qn(attr), None)


def set_style_font(style, size=BODY_PT):
    style.font.name = FONT
    style.font.size = Pt(size)
    style.font.color.rgb = BLACK
    rpr = style.element.get_or_add_rPr()
    fonts = rpr.find(qn("w:rFonts"))
    if fonts is None:
        fonts = OxmlElement("w:rFonts")
        rpr.insert(0, fonts)
    for attr in ("w:ascii", "w:hAnsi", "w:eastAsia", "w:cs"):
        fonts.set(qn(attr), FONT)
    for attr in ("w:asciiTheme", "w:hAnsiTheme", "w:eastAsiaTheme", "w:cstheme"):
        fonts.attrib.pop(qn(attr), None)
    lang = rpr.find(qn("w:lang"))
    if lang is None:
        lang = OxmlElement("w:lang")
        rpr.append(lang)
    lang.set(qn("w:val"), "en-AU")


def tidy_spacing(paragraph, before=0, after=0, keep_with_next=False):
    pf = paragraph.paragraph_format
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.line_spacing_rule = WD_LINE_SPACING.SINGLE
    pf.widow_control = True
    pf.keep_with_next = keep_with_next


def add_bottom_border(paragraph):
    """A single black rule under the heading paragraph only (no box, no shading)."""
    ppr = paragraph._p.get_or_add_pPr()
    borders = ppr.find(qn("w:pBdr"))
    if borders is None:
        borders = OxmlElement("w:pBdr")
        ppr.append(borders)
    for old in borders.findall(qn("w:bottom")):
        borders.remove(old)
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "single")
    bottom.set(qn("w:sz"), "6")
    bottom.set(qn("w:space"), "1")
    bottom.set(qn("w:color"), "000000")
    borders.append(bottom)


def setup_document():
    doc = Document()
    section = doc.sections[0]
    section.orientation = WD_ORIENT.PORTRAIT
    section.page_width, section.page_height = Cm(21.0), Cm(29.7)
    section.top_margin, section.bottom_margin = Cm(1.5), Cm(1.5)
    section.left_margin, section.right_margin = Cm(1.7), Cm(1.7)
    section.header_distance = section.footer_distance = Cm(0.8)

    normal = doc.styles["Normal"]
    set_style_font(normal)
    pf = normal.paragraph_format
    pf.space_before, pf.space_after = Pt(0), Pt(0)
    pf.line_spacing_rule = WD_LINE_SPACING.SINGLE
    pf.widow_control = True

    bullet = doc.styles["List Bullet"]
    set_style_font(bullet)
    bpf = bullet.paragraph_format
    bpf.space_before, bpf.space_after = Pt(0), Pt(0)
    bpf.line_spacing_rule = WD_LINE_SPACING.SINGLE
    bpf.left_indent, bpf.first_line_indent = Cm(0.5), Cm(-0.4)
    bpf.widow_control = True

    candidate = RESUME["candidate"]
    props = doc.core_properties
    props.author = candidate["full_name"]
    props.title = f"{candidate['full_name']} Resume"
    props.subject = candidate["generic_job_title"]
    props.comments = props.keywords = props.category = ""
    props.last_modified_by = candidate["full_name"]
    return doc


def add_text(doc, text, size=BODY_PT, bold=False, italic=False, align=None, before=0, after=0, keep_with_next=False):
    p = doc.add_paragraph()
    tidy_spacing(p, before, after, keep_with_next)
    if align is not None:
        p.alignment = align
    set_run_font(p.add_run(text), size, bold, italic)
    return p


def add_bullet(doc, text, label=""):
    p = doc.add_paragraph(style="List Bullet")
    tidy_spacing(p)
    if label:
        set_run_font(p.add_run(f"{label}: "), bold=True)
    set_run_font(p.add_run(text), bold=False)
    return p


def add_heading(doc, text):
    p = add_text(doc, text.upper(), size=BODY_PT, bold=True, before=10, after=3, keep_with_next=True)
    add_bottom_border(p)
    return p


def joined(*parts, sep=" | "):
    return sep.join(str(p).strip() for p in parts if p and str(p).strip())


def date_range(start, end):
    if start and end:
        return f"{start} to {end}"
    return start or end or ""


def build(doc):
    c = RESUME["candidate"]
    add_text(doc, c["full_name"].upper(), size=22, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER)
    if c["generic_job_title"]:
        add_text(doc, c["generic_job_title"], size=12, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER, before=2)
    contact = joined(c["location"], c["phone"], c["email"])
    if contact:
        add_text(doc, contact, align=WD_ALIGN_PARAGRAPH.CENTER, before=2)
    if c["linkedin"]:
        add_text(doc, c["linkedin"], align=WD_ALIGN_PARAGRAPH.CENTER)

    if RESUME["professional_summary"]:
        add_heading(doc, "Professional Summary")
        add_text(doc, RESUME["professional_summary"])

    if RESUME["key_skills"]:
        add_heading(doc, "Key Skills")
        for skill in RESUME["key_skills"]:
            add_bullet(doc, skill)

    if RESUME["professional_experience"]:
        add_heading(doc, "Professional Experience")
        for i, role in enumerate(RESUME["professional_experience"]):
            add_text(doc, joined(role["job_title"], role["employer"], role["location"]), bold=True, before=0 if i == 0 else 8, keep_with_next=True)
            dates = date_range(role["start_date"], role["end_date"])
            if dates:
                add_text(doc, dates, keep_with_next=True)
            if role["scope_statement"]:
                add_text(doc, role["scope_statement"], italic=True, before=2, keep_with_next=bool(role["achievements"]))
            for item in role["achievements"]:
                add_bullet(doc, item)

    if RESUME["education_and_training"]:
        add_heading(doc, "Education and Training")
        for i, ed in enumerate(RESUME["education_and_training"]):
            line = joined(ed["qualification"], ed["institution"], ed["location"], ed["completion_date"])
            add_text(doc, line, bold=False, before=0 if i == 0 else 4, keep_with_next=bool(ed["details"]))
            if ed["details"]:
                add_text(doc, ed["details"])

    if RESUME["awards"]:
        add_heading(doc, "Awards")
        for a in RESUME["awards"]:
            text = joined(a["award_name"], a["issuing_organisation"], a["year"], sep=", ")
            add_bullet(doc, text + (f". {a['details']}" if a["details"] else ""))

    if RESUME["certifications"]:
        add_heading(doc, "Certifications")
        for cert in RESUME["certifications"]:
            expiry = f"expires {cert['expiry_date']}" if cert["expiry_date"] else ""
            add_bullet(doc, joined(cert["certification_name"], cert["issuing_body"], cert["year_obtained"], expiry, sep=", "))

    if RESUME["technical_skills"]:
        add_heading(doc, "Technical Skills")
        for group in RESUME["technical_skills"]:
            add_bullet(doc, ", ".join(group["skills"]), label=group["category"])

    if RESUME["additional_information"]:
        add_heading(doc, "Additional Information")
        for item in RESUME["additional_information"]:
            add_bullet(doc, item["details"], label=item["category"])


def main():
    out_dir = sys.argv[1] if len(sys.argv) > 1 else os.getcwd()
    os.makedirs(out_dir, exist_ok=True)
    c = RESUME["candidate"]
    filename = sanitise_filename(c["full_name"], c["generic_job_title"], __FALLBACK__)
    path = os.path.join(out_dir, filename)
    doc = setup_document()
    build(doc)
    doc.save(path)
    if not os.path.isfile(path) or os.path.getsize(path) == 0:
        print(f"Saving failed: {path} was not written.", file=sys.stderr)
        return 1
    print(f"Document created successfully: {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
'''


def build_script(data, fallback_title=""):
    """Complete Python source for the approved, normalised resume `data`."""
    name = (data.get("candidate") or {}).get("full_name") or "the candidate"
    name = "".join(ch for ch in name if ch.isalnum() or ch in " .'-") or "the candidate"
    # Data goes in last so resume text can never be mistaken for a placeholder.
    return (
        _TEMPLATE.replace("__NAME__", name)
        .replace("__SANITISE__", inspect.getsource(sanitise_filename))
        .replace("__FALLBACK__", repr(fallback_title or ""))
        .replace("__DATA__", pprint.pformat(data, width=110, sort_dicts=False))
    )
